#!/usr/bin/env bash
# Build a clickable "Gallery Wall Studio" app that starts the local server if it isn't
# running and opens the studio in your browser.
#
#   ./launcher/make-app.sh                       # puts the app on your Desktop
#   ./launcher/make-app.sh --dest /Applications  # put it somewhere else
#
# Rerun it if you move this folder: the app remembers where the repo lives.
# To change the icon, edit launcher/icon.html, run `node launcher/render-icon.mjs`, then rerun this.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/.." && pwd)"
DEST="$HOME/Desktop"
while [ $# -gt 0 ]; do
  case "$1" in
    --dest) DEST="$2"; shift 2 ;;
    -h|--help) sed -n '2,9p' "$0"; exit 0 ;;
    *) echo "unknown option: $1 (try --help)" >&2; exit 1 ;;
  esac
done

APP="$DEST/Gallery Wall Studio.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$HERE/GalleryWallStudio.icns" "$APP/Contents/Resources/GalleryWallStudio.icns"

cat > "$APP/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Gallery Wall Studio</string>
  <key>CFBundleDisplayName</key><string>Gallery Wall Studio</string>
  <key>CFBundleIdentifier</key><string>local.angelscrydata.gallery-wall-studio</string>
  <key>CFBundleVersion</key><string>1.0</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>launch</string>
  <key>CFBundleIconFile</key><string>GalleryWallStudio</string>
  <key>LSMinimumSystemVersion</key><string>11.0</string>
  <!-- Without these, macOS silently blocks the app from the folder the studio lives in instead of asking. -->
  <key>NSDocumentsFolderUsageDescription</key><string>Gallery Wall Studio runs its local server and saves your walls in its folder.</string>
  <key>NSDesktopFolderUsageDescription</key><string>Gallery Wall Studio runs its local server and saves your walls in its folder.</string>
  <key>NSDownloadsFolderUsageDescription</key><string>Gallery Wall Studio runs its local server and saves your walls in its folder.</string>
</dict>
</plist>
PLIST

{
  echo '#!/bin/bash'
  echo '# Generated by launcher/make-app.sh. Starts the Gallery Wall Studio server if needed, then opens it.'
  printf 'REPO=%q\n' "$REPO"
  cat <<'LAUNCH'
PORT="${GALLERY_WALL_PORT:-4173}"
URL="http://localhost:$PORT/"
# Apps opened from Finder get a bare PATH; add the usual places Node is installed.
export PATH="/opt/homebrew/bin:/usr/local/bin:$HOME/.volta/bin:$HOME/.local/bin:/usr/bin:/bin:/usr/sbin:/sbin:$PATH"
# Log outside the repo: macOS may not let this app's shell write into Documents.
LOG="$HOME/Library/Logs/gallery-wall-studio.log"

alert() { osascript -e "display alert \"Gallery Wall Studio\" message \"$1\" as critical" >/dev/null; }
up() { curl -s -o /dev/null -m 1 "${URL}api/projects/deleted"; }

if ! up; then
  NODE="$(command -v node || true)"
  if [ -z "$NODE" ]; then
    alert "Couldn't find Node.js. Install it (for example with Homebrew: brew install node), then try again."
    exit 1
  fi
  # Start the server with Node directly rather than npm: macOS privacy rules often stop an
  # app's shell from reading files in Documents, but let Node in once you allow it.
  PORT="$PORT" nohup "$NODE" "$REPO/scripts/dev.mjs" >"$LOG" 2>&1 &
  for _ in $(seq 1 60); do up && break; sleep 0.5; done
  if ! up; then
    alert "The studio's server didn't start. If this is a fresh copy, run npm install in $REPO first. If you moved the folder, rerun launcher/make-app.sh. Details are in ~/Library/Logs/gallery-wall-studio.log"
    exit 1
  fi
fi

[ -n "${GALLERY_WALL_NO_OPEN:-}" ] || open "$URL"
LAUNCH
} > "$APP/Contents/MacOS/launch"
chmod +x "$APP/Contents/MacOS/launch"

touch "$APP"   # nudge Finder to pick up the new icon
echo "Made: $APP"
